//! The About window: a separate top-level window, created only on request and reused if already
//! open, never on the startup path. Laid out after concept sheet 5
//! (`docs/design/concepts/sheet-5-about-window.webp`): the stacked logo, the tagline, the
//! "Faster than light" divider, the product facts, then environment facts useful for support
//! requests. The logo is the one piece of brand artwork in the app (owner-approved, see
//! `docs/design/DESIGN_DIRECTION.md`), rasterized only when this window opens.

